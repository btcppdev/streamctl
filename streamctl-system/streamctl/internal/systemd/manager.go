func (m *Manager) normalizeBufsize() string {
	video := m.normalizeVideoBitrate()
	if strings.HasSuffix(video, "k") {
		n, err := strconv.Atoi(strings.TrimSuffix(video, "k"))
		if err == nil && n > 0 {
			return strconv.Itoa(n*2) + "k"
		}
	}
	return video
}
