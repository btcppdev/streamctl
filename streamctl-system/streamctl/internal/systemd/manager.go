func (m *Manager) renderCleanupScript(s *db.Stream) string {
	var b strings.Builder
	b.WriteString("#!/run/current-system/sw/bin/bash\n")
	b.WriteString("set -euo pipefail\n")
	b.WriteString("export PATH=/run/current-system/sw/bin:/bin\n")
	b.WriteString(m.renderCleanupScriptBody(s))
	return b.String()
}

func (m *Manager) renderCleanupScriptBody(s *db.Stream) string {
	var b strings.Builder
	for _, v := range s.Videos {
		if !isRemoteClip(v) {
			continue
		}
		for _, path := range m.remoteCachePaths(s, v) {
			b.WriteString("/run/current-system/sw/bin/rm -f -- ")
			b.WriteString(shellQuote(path))
			b.WriteString("\n")
		}
	}
	return b.String()
}

func (m *Manager) needsPrefetch(s *db.Stream) bool {
	for _, v := range s.Videos {
		if isRemoteClip(v) {
			return true
		}
	}
	return false
}

// Imported talks are finished renders; prefetch and stream their original bytes.
func (m *Manager) normalizeStream(s *db.Stream) bool {
	return m.Normalize && !s.AutoScheduled
}

func (m *Manager) localClipPath(s *db.Stream, source string) string {
	if isRemoteClip(source) {
		if m.normalizeStream(s) {
			return m.normalizedClipPath(source)
		}
		return filepath.Join(m.CacheDir, source)
	}
	return filepath.Join(m.VideoDir, source)
}

func (m *Manager) rawRemoteClipPath(source string) string {
	return filepath.Join(m.CacheDir, source)
}

func (m *Manager) normalizedClipPath(source string) string {
	ext := filepath.Ext(source)
	base := strings.TrimSuffix(source, ext)
	return filepath.Join(m.CacheDir, "normalized", base+".mp4")
}

func (m *Manager) normalizedRemoteClipPath(source string) string {
	return strings.Replace(source, "/recordings/edits/", "/recordings/normalized/", 1)
}

func (m *Manager) remoteObjectPath(source string) string {
	return strings.TrimRight(m.Remote, "/") + slashForRemote(m.Remote) + source
}

func (m *Manager) remoteCachePaths(s *db.Stream, source string) []string {
	paths := []string{m.rawRemoteClipPath(source)}
	if m.normalizeStream(s) {
		paths = append(paths, m.normalizedClipPath(source))
	}
	return paths
}

func isRemoteClip(source string) bool {
	return strings.Contains(source, "/")
}

func slashForRemote(remote string) string {
	if strings.HasSuffix(remote, "/") || strings.HasSuffix(remote, ":") {
		return ""
	}
	return "/"
}

func buildTeeArg(endpoints []db.Endpoint) string {
	var parts []string
	for _, e := range endpoints {
		if !e.Enabled {
			continue
		}
		switch e.Type {
		case "youtube_hls":
			parts = append(parts, youtubeHLSTeeArg(e.RtmpURL))
		default:
			url := strings.TrimRight(e.RtmpURL, "/") + "/" + e.StreamKey
			parts = append(parts, rtmpTeeArg(url))
		}
	}
	return strings.Join(parts, "|")
}

func rtmpTeeArg(url string) string {
	return fmt.Sprintf(
		"[f=fifo:fifo_format=flv:queue_size=600:drop_pkts_on_overflow=1:attempt_recovery=1:recover_any_error=1:restart_with_keyframe=1:recovery_wait_time=5:max_recovery_attempts=100000:onfail=ignore]%s",
		url,
	)
}

func youtubeHLSTeeArg(template string) string {
	base := strings.TrimSpace(template)
	segment := hlsUploadURL(base, "segment-%06d.ts")
	playlist := hlsUploadURL(base, "index.m3u8")
	return fmt.Sprintf(
		"[f=hls:method=PUT:http_persistent=1:hls_time=4:hls_list_size=8:hls_flags=delete_segments+omit_endlist:hls_segment_filename=%s]%s",
		teeOptionEscape(segment),
		playlist,
	)
}

func hlsUploadURL(template, name string) string {
	if strings.HasSuffix(template, "file=") {
		return template + name
	}
	if strings.Contains(template, "file=") {
		return template + name
	}
	if strings.Contains(template, "?") {
		return template + "&file=" + name
	}
	return template + "?file=" + name
}

func teeOptionEscape(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, ":", `\:`)
	return s
}

func enabledEndpoints(eps []db.Endpoint) []db.Endpoint {
	var out []db.Endpoint
	for _, e := range eps {
		if e.Enabled {
			out = append(out, e)
		}
	}
	return out
}

// ---------- helpers ----------

func systemctl(args ...string) error {
	cmd := exec.Command("systemctl", args...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("systemctl %s: %w: %s", strings.Join(args, " "), err, string(out))
	}
	return nil
}

func writeFile(path, contents string) error {
	return writeFileMode(path, contents, 0600)
}

func writeFileMode(path, contents string, mode os.FileMode) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp-")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	defer func() {
		_ = os.Remove(tmpPath)
	}()
	if _, err := tmp.Write([]byte(contents)); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Chmod(mode); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpPath, path)
}

func appendError(existing string, err error) string {
	if err == nil {
		return existing
	}
	msg := strings.TrimSpace(err.Error())
	if existing == "" {
		return msg
	}
	return existing + "\n" + msg
}

// shellQuote wraps a value in single quotes for safe inclusion in an ExecStart line.
// systemd does its own quoting; we use this for argv values containing spaces.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// shellEscape strips problematic chars from human-facing description strings.
func shellEscape(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "\n", " "), "\r", " ")
}

func systemdQuote(s string) string {
	return `"` + strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), `"`, `\"`) + `"`
}

func shellDoubleQuoteContent(s string) string {
	s = strings.ReplaceAll(strings.ReplaceAll(s, "\n", " "), "\r", " ")
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	s = strings.ReplaceAll(s, "$", `\$`)
	s = strings.ReplaceAll(s, "`", "\\`")
	return s
}

