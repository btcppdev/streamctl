// Manager generates systemd service + timer units for streams,
// and reloads/enables/disables them via systemctl.
type Manager struct {
	UnitDir        string // e.g. /run/systemd/system
	UnitPrefix     string // e.g. "streamctl-"
	RunUser        string
	VideoDir       string
	CacheDir       string
	HLSDir         string
	Remote         string // rclone remote, e.g. spaces:bucket
	RcloneConfig   string
	NotifyEmail    string
	SendmailPath   string
	CleanupCache   bool
	Normalize      bool
	VideoBitrate   string
	AudioBitrate   string
	NostrKeyDir    string
	PublicBaseURL  string
	SelfPath       string
	BTCPPAPIBase   string
	BTCPPTokenFile string
}

type UnitLog struct {
	Label       string
	UnitName    string
	LoadedState string
	ActiveState string
	SubState    string
	Result      string
	Since       string
	Journal     string
	Error       string
}

// StreamRuntime is the bounded set of systemd service properties exported to
// Prometheus. IPAccounting tracks traffic generated by the ffmpeg service's
// cgroup, including each RTMP/HLS destination written by the tee muxer.
type StreamRuntime struct {
	Active       bool
	Failed       bool
	Result       string
	IngressBytes float64
	EgressBytes  float64
}

